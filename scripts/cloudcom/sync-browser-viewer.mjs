// Reuse the pinned upstream viewer without importing its native runtime.
// --check fails when an upstream update changes any generated browser source.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, dirname, relative, extname } from 'node:path';
const source = resolve('apps/viewer/src');
const target = resolve('apps/web/src/components/cloudcom/browserDesktop/upstream');
const pending = ['components/DesktopViewer.tsx'];
const seen = new Set();
const check = process.argv.includes('--check');
while (pending.length) {
  const name = pending.pop();
  if (seen.has(name)) continue;
  seen.add(name);
  let content = readFileSync(resolve(source, name), 'utf8').replace(/\r\n/g, '\n');
  for (const match of content.matchAll(/(?:from\s*|import\s*\()\s*['"](\.[^'"]+)['"]/g)) {
    const base = resolve(source, dirname(name), match[1]);
    const file = [base, `${base}.ts`, `${base}.tsx`].find(p => existsSync(p) && extname(p));
    if (!file || !file.startsWith(source + '/'.replace('/', process.platform === 'win32' ? '\\' : '/'))) throw new Error(`Unresolved viewer dependency: ${match[1]}`);
    pending.push(relative(source, file).replaceAll('\\', '/'));
  }
  const adapter = relative(dirname(resolve(target, name)), resolve(target, '../platform')).replaceAll('\\', '/');
  content = content.replaceAll('@tauri-apps/api/core', adapter).replaceAll('@tauri-apps/plugin-clipboard-manager', adapter);
  if (/\bfetch\(|= fetch\b/.test(content)) {
    const network = relative(dirname(resolve(target, name)), resolve(target, '../browserFetch')).replaceAll('\\', '/');
    content = `import { browserFetch as fetch } from '${network}';\n` + content;
  }
  if (name === 'components/DesktopViewer.tsx') {
    content = content.replace('interface Props {', 'interface Props {\n  closing?: boolean;');
    content = content.replace('params, onDisconnect, onError }: Props', 'params, onDisconnect, onError, closing = false }: Props');
    // Pause input/connection immediately while server-confirmed End is pending.
    const returnMarker = '\n  return (';
    const at = content.lastIndexOf(returnMarker);
    if (at < 0) throw new Error('Viewer render attachment point changed');
    content = content.slice(0, at) + `\n  useEffect(() => {\n    if (!closing) return;\n    userDisconnectRef.current = true;\n    stopReconnect();\n    releaseAllKeys();\n    webrtcRef.current?.close();\n    wsCleanupRef.current?.();\n    vncSessionRef.current?.close();\n  }, [closing, releaseAllKeys, stopReconnect]);\n` + content.slice(at);
  }
  content = '// Generated by scripts/cloudcom/sync-browser-viewer.mjs; do not edit. Upstream AGPL-3.0.\n' + content;
  const out = resolve(target, name);
  if (check) {
    if (!existsSync(out) || readFileSync(out, 'utf8').replace(/\r\n/g, '\n') !== content) throw new Error(`Browser viewer needs reviewed resync: ${name}`);
  } else { mkdirSync(dirname(out), { recursive: true }); writeFileSync(out, content); }
}
console.log(`${check ? 'Verified' : 'Generated'} ${seen.size} upstream browser viewer modules`);
